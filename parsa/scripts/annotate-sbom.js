// Completes parsa's post-build SBOM after prune-go-sbom.js has cut it down to what the binaries link.
//
// cdxgen sees microsoft/TypeScript/tsc and the generated shim as local replacements at v0.0.0, which
// names neither the commit parsa is built from nor the patch applied to it. This script gives both
// the pinned commit as a Go pseudo-version (v0.0.0-<commit time>-<12 hex>), records the commit and
// every patch in parsa/patches as the TypeScript component's pedigree, names and versions the parsa
// component itself and names AppThreat as its supplier, marks every component required (each one is
// linked into the binaries), and drops the properties that only describe the build machine (local
// directories, cdxgen internals).
//
// The Go standard library gets the NVD CPE for Go and no purl: prune-go-sbom.js names it
// pkg:golang/stdlib, which Go's vulnerability tools use but the purl golang definition rejects
// (it requires a namespace), so cdxgen's validator fails the whole SBOM on it.
//
// Usage: node annotate-sbom.js <sbom.cdx.json> <parsa version> [<repository url> <commit>]
// The repository url and commit, when given, make each patch's url point at the file in that commit.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TSC = "github.com/microsoft/TypeScript/tsc";
const SHIM = "github.com/microsoft/TypeScript/tsc/shim";
const PARSA = "github.com/AppThreat/atom-parsetools/parsa";

// The purl cdxgen writes for a Go module: lowercased path, version as given.
export function golangPurl(modulePath, version) {
  const name = modulePath.toLowerCase();
  return version ? `pkg:golang/${name}@${encodeURIComponent(version)}` : `pkg:golang/${name}`;
}

// The Go pseudo-version of a commit: v0.0.0-<UTC yyyymmddhhmmss>-<first 12 hex digits>.
export function pseudoVersion(commit, commitTime) {
  return `v0.0.0-${commitTime}-${commit.slice(0, 12)}`;
}

function dropBuildMachineProperties(component) {
  if (!component.properties) return;
  component.properties = component.properties.filter(
    (p) => p.name !== "cdx:go:local_dir" && !p.name.startsWith("internal:"),
  );
  if (!component.properties.length) delete component.properties;
}

// Moves a component to a new bom-ref and purl (none when purl is undefined), and every dependency
// entry with it.
function rename(bom, component, purl, ref = purl) {
  const old = component["bom-ref"];
  if (purl) component.purl = purl;
  else delete component.purl;
  component["bom-ref"] = ref;
  for (const dep of bom.dependencies || []) {
    if (dep.ref === old) dep.ref = ref;
    if (dep.dependsOn) dep.dependsOn = dep.dependsOn.map((r) => (r === old ? ref : r));
  }
}

export function annotate(bom, { version, commit, commitTime, patches, repoUrl, repoCommit }) {
  const tscVersion = pseudoVersion(commit, commitTime);
  const meta = bom.metadata?.component;
  if (meta) {
    meta.name = "parsa";
    meta.group = "";
    meta.version = version;
    meta.description = "parse for atom: atom-parsetools' native parsers";
    rename(bom, meta, golangPurl(PARSA, `v${version}`));
    dropBuildMachineProperties(meta);
  }
  if (bom.metadata) {
    bom.metadata.supplier = { name: "Team AppThreat", url: ["https://github.com/AppThreat"] };
  }
  for (const c of bom.components || []) {
    dropBuildMachineProperties(c);
    c.scope = "required";
    if (c.name === TSC) {
      c.version = tscVersion;
      rename(bom, c, golangPurl(TSC, tscVersion));
      c.externalReferences = [
        { type: "vcs", url: `https://github.com/microsoft/TypeScript/tree/${commit}/tsc` },
      ];
      c.pedigree = {
        commits: [{ uid: commit, url: `https://github.com/microsoft/TypeScript/commit/${commit}` }],
        patches: patches.map((p) => ({
          type: "unofficial",
          diff: {
            text: { contentType: "text/x-diff", content: p.content },
            ...(repoUrl && repoCommit ? { url: `${repoUrl}/blob/${repoCommit}/parsa/patches/${p.name}` } : {}),
          },
        })),
        notes: "Built from the tsc/ directory of microsoft/TypeScript at the pinned commit with the patches in parsa/patches applied.",
      };
    } else if (c.purl?.startsWith("pkg:golang/stdlib@")) {
      const goVersion = c.version.replace(/^v/, "");
      c.group = "golang.org";
      c.description = "Go standard library";
      c.cpe = `cpe:2.3:a:golang:go:${goVersion}:*:*:*:*:*:*:*`;
      rename(bom, c, undefined, `go-stdlib@${goVersion}`);
    } else if (c.name === SHIM) {
      c.version = tscVersion;
      rename(bom, c, golangPurl(SHIM, tscVersion));
      c.description = `Go linkname shims over the internal packages of microsoft/TypeScript tsc/ at ${commit}, generated by parsa/tools/gen_shims`;
      c.licenses = [{ license: { id: "Apache-2.0" } }];
    }
  }
  return bom;
}

function typescriptCommit() {
  const dir = path.join(here, "_deps", "TypeScript");
  const out = execFileSync("git", ["-C", dir, "log", "-1", "--format=%H %cd", "--date=format-local:%Y%m%d%H%M%S"], {
    encoding: "utf-8",
    env: { ...process.env, TZ: "UTC" },
  }).trim();
  const [commit, commitTime] = out.split(" ");
  const pin = fs.readFileSync(path.join(here, "third_party", "typescript.pin"), "utf-8").trim();
  if (commit !== pin) {
    throw new Error(`_deps/TypeScript is at ${commit}, not the pin ${pin}; run scripts/fetch-typescript.sh`);
  }
  return { commit, commitTime };
}

function readPatches() {
  const dir = path.join(here, "patches");
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".patch"))
    .sort()
    .map((name) => ({ name, content: fs.readFileSync(path.join(dir, name), "utf-8") }));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [sbomFile, version, repoUrl, repoCommit] = process.argv.slice(2);
  if (!sbomFile || !version) {
    console.error("usage: node annotate-sbom.js <sbom.cdx.json> <parsa version> [<repository url> <commit>]");
    process.exit(2);
  }
  const bom = JSON.parse(fs.readFileSync(sbomFile, "utf-8"));
  annotate(bom, { version, ...typescriptCommit(), patches: readPatches(), repoUrl, repoCommit });
  fs.writeFileSync(sbomFile, `${JSON.stringify(bom, null, 2)}\n`);
  console.log(`${sbomFile}: parsa ${version}, TypeScript ${typescriptCommit().commit}, ${readPatches().length} patch(es)`);
}
